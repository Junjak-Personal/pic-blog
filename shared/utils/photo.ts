/** 사진의 «동일성» 판정 — 같은 사진이 두 번 올라오는 걸 막는 데 쓴다. */

/**
 * 「같은 사진인가」의 판정 키 — 촬영 시각 + 좌표.
 *
 * 파일명은 쓰지 않는다. 기기가 IMG_0001 을 재사용하고, 에어드롭·메신저·다운로드를
 * 거치면 이름이 바뀐다. 애초에 서버는 원본 파일명을 저장하지도 않아서, 파일명 기준으로
 * 하려면 열을 새로 만들고 그때부터 쌓아야 하고 이미 올라간 사진은 영영 판정할 수 없다.
 * 반대로 EXIF 는 이름을 바꾸든 다시 저장하든 남고, 기존 사진 전부가 shot_at·lat·lng 를
 * 이미 갖고 있어 새 열 없이 오늘 당장 비교된다.
 *
 * 🔴 shot_at 은 초 단위라 «연사»는 같은 키가 될 수 있다 (같은 초 · 거의 같은 좌표).
 *    그래서 이 키에 걸린 사진은 조용히 버리지 않고 제외 목록에 사유와 함께 남긴다
 *    (설계문서 §8 — 조용한 실패 금지).
 *
 * 좌표는 6자리에서 끊는다 — 약 0.1m. 같은 파일을 다시 읽으면 값이 그대로라 사실
 * 반올림이 필요 없지만, 서버를 한 번 거쳐 온 값과 비교하므로 자릿수를 맞춰 둔다.
 */
export function photoKey(p: { shotAt: string; lat: number; lng: number }) {
  return `${p.shotAt}|${p.lat.toFixed(6)}|${p.lng.toFixed(6)}`
}
